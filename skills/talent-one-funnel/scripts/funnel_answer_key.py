#!/usr/bin/env python3
"""Funnel answer key: compute stage conversion and the weakest transition from a CSV.

The Oracle's worked example used to carry a hand-typed answer key that was shifted one
stage and named the wrong bottleneck. This script owns those numbers instead: it computes
every transition from the cumulative counts, compares each one with a benchmark range,
and writes the result into the prompt between the ANSWER-KEY markers. `check` fails when
the embedded block drifts from what the data says, so the key can never be hand-edited
out of step again. Standard library only; no network, no model calls.

    python funnel_answer_key.py diagnose [CSV] [--benchmarks CSV] [--json OUT]
    python funnel_answer_key.py write    [--prompt MD] [CSV] [--benchmarks CSV]
    python funnel_answer_key.py check    [--prompt MD] [CSV] [--benchmarks CSV]
    python funnel_answer_key.py check-narrative TEXT_MD --diagnosis JSON

Defaults: data/sample-funnel.csv, data/teaching-benchmarks.csv and
references/oracle-project-prompt.md inside this skill. Exit codes: 0 clean, 1 drift or
findings, 2 invalid input. The CSV contract is funnel_verifier.py's (stage, count,
pass_pct_of_prior, role, quarter; one cohort; cumulative counts that never increase).
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SKILL = HERE.parent
sys.path.insert(0, str(HERE))
from funnel_verifier import analyze

DEFAULT_CSV = SKILL / "data" / "sample-funnel.csv"
DEFAULT_BENCH = SKILL / "data" / "teaching-benchmarks.csv"
DEFAULT_PROMPT = SKILL / "references" / "oracle-project-prompt.md"
BEGIN = "<!-- ANSWER-KEY:BEGIN (generated by scripts/funnel_answer_key.py; do not edit by hand) -->"
END = "<!-- ANSWER-KEY:END -->"
ARROW = "→"


def _read_csv(path: Path) -> list[dict]:
    with path.open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def load_benchmarks(path: Path) -> dict[tuple[str, str], dict]:
    out: dict[tuple[str, str], dict] = {}
    for row in _read_csv(path):
        key = (row["from_stage"].strip().casefold(), row["to_stage"].strip().casefold())
        low, high = float(row["low_pct"]), float(row["high_pct"])
        if not 0 <= low <= high <= 100:
            raise ValueError(
                f"benchmark {row['from_stage']} -> {row['to_stage']}: bad range"
            )
        out[key] = {
            "from": row["from_stage"].strip(),
            "to": row["to_stage"].strip(),
            "low": low,
            "high": high,
            "label": row.get("benchmark_label", "").strip(),
        }
    return out


def _fmt(x: float) -> str:
    return f"{x:.1f}"


def _range(b: dict) -> str:
    return f"{b['low']:g}-{b['high']:g}%"


def diagnose(funnel: Path, bench: Path) -> dict:
    report = analyze(_read_csv(funnel))  # validates the cohort; raises ValueError
    benches = load_benchmarks(bench)
    stages = report["stages"]
    transitions = []
    for prev, cur in zip(stages, stages[1:]):
        b = benches.get((prev["stage"].casefold(), cur["stage"].casefold()))
        rate = cur["pass_pct"]
        t = {
            "from": prev["stage"],
            "to": cur["stage"],
            "entered": prev["count"],
            "advanced": cur["count"],
            "rate": None if rate is None else round(rate, 1),
            "benchmark": None if b is None else {"low": b["low"], "high": b["high"]},
        }
        if rate is None or b is None:
            t["read"], t["gap_pts"] = (
                ("no data" if rate is None else "no benchmark"),
                None,
            )
        elif rate < b["low"]:
            t["read"], t["gap_pts"] = "below range", round(rate - b["low"], 1)
        elif rate > b["high"]:
            t["read"], t["gap_pts"] = "above range", round(rate - b["high"], 1)
        else:
            t["read"], t["gap_pts"] = "within range", 0.0
        transitions.append(t)
    last = stages[-1]["stage"].casefold()
    present = {s["stage"].casefold() for s in stages}
    missing = [
        {
            "from": b["from"],
            "to": b["to"],
            "benchmark": {"low": b["low"], "high": b["high"]},
        }
        for (f, to), b in benches.items()
        if f == last and to not in present
    ]
    below = [t for t in transitions if t["read"] == "below range"]
    weakest = min(below, key=lambda t: t["gap_pts"]) if below else None
    return {
        "role": report["role"],
        "quarter": report["quarter"],
        "stages": [{"stage": s["stage"], "count": s["count"]} for s in stages],
        "transitions": transitions,
        "not_in_file": missing,
        "weakest": None
        if weakest is None
        else {
            k: weakest[k]
            for k in ("from", "to", "entered", "advanced", "rate", "gap_pts")
        }
        | {"benchmark": weakest["benchmark"]},
        "verifier_findings": report["findings"],
    }


def render_block(d: dict, funnel_name: str, bench_name: str) -> str:
    first, last = d["stages"][0], d["stages"][-1]
    lines = [
        BEGIN,
        (
            f"Source: `{funnel_name}` against `{bench_name}`; {d['role']}, {d['quarter']}; "
            f"{first['count']} {first['stage'].lower()} in, {last['count']} {last['stage'].lower()}"
            f"{'s' if last['stage'].lower() == 'offer' else ''} out."
        ),
        "",
        "| Stage | Count | Pass % of prior (computed) |",
        "|---|---|---|",
        f"| {first['stage']} | {first['count']} | n/a |",
    ]
    for t in d["transitions"]:
        rate = "n/a" if t["rate"] is None else f"{_fmt(t['rate'])}%"
        lines.append(f"| {t['to']} | {t['advanced']} | {rate} |")
    lines += [
        "",
        "| Transition | Actual | Teaching benchmark | Gap to range | Read |",
        "|---|---|---|---|---|",
    ]
    w = d["weakest"]
    for t in d["transitions"]:
        name = f"{t['from']} {ARROW} {t['to']}"
        actual = (
            "n/a"
            if t["rate"] is None
            else f"{_fmt(t['rate'])}% ({t['advanced']} of {t['entered']})"
        )
        bench = "none" if t["benchmark"] is None else _range(t["benchmark"])
        if t["gap_pts"] is None:
            gap = "n/a"
        elif t["gap_pts"] == 0:
            gap = "within"
        else:
            gap = f"{t['gap_pts']:+.1f} pts"
        read = t["read"]
        if w and t["from"] == w["from"] and t["to"] == w["to"]:
            read = "weakest transition"
            lines.append(
                f"| **{name}** | **{actual}** | **{bench}** | **{gap}** | **{read}** |"
            )
        else:
            lines.append(f"| {name} | {actual} | {bench} | {gap} | {read} |")
    for m in d["not_in_file"]:
        lines.append(
            f"| {m['from']} {ARROW} {m['to']} | not in the file | {_range(m['benchmark'])} | n/a | "
            "no data: the file stops at this stage |"
        )
    lines.append("")
    if w:
        lines.append(
            f"**Weakest transition:** {w['from']} {ARROW} {w['to']}: {_fmt(w['rate'])}% "
            f"({w['advanced']} of {w['entered']}) against a {_range(w['benchmark'])} teaching range, "
            f"{abs(w['gap_pts']):.1f} points below its low end."
        )
    else:
        lines.append(
            "**Weakest transition:** none. No single bottleneck: every transition with a "
            "benchmark is within or above its range."
        )
    if d["verifier_findings"]:
        lines.append("")
        lines.append(
            "**Reported percentages that disagree with the counts:** "
            + "; ".join(d["verifier_findings"])
        )
    lines.append(END)
    return "\n".join(lines)


def _rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(SKILL).as_posix()
    except ValueError:
        return path.name


def _embedded(text: str) -> tuple[int, int]:
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < start:
        raise ValueError("ANSWER-KEY markers not found in the prompt")
    return start, end + len(END)


NUM = re.compile(r"(?<![\w.])(\d{1,3}(?:\.\d+)?)\s*%")
OF = re.compile(r"\b(\d+)\s+of\s+(\d+)\b")


def check_narrative(text: str, d: dict) -> list[str]:
    """Every percentage and every 'N of M' in a narrative must trace to the diagnosis."""
    allowed: set[float] = set()
    pairs: set[tuple[int, int]] = set()
    for t in d["transitions"] + d["not_in_file"]:
        if t.get("rate") is not None:
            allowed |= {round(t["rate"], 1), float(round(t["rate"]))}
            pairs.add((t["advanced"], t["entered"]))
        b = t.get("benchmark")
        if b:
            allowed |= {b["low"], b["high"], (b["low"] + b["high"]) / 2}
        if t.get("gap_pts"):
            allowed |= {abs(t["gap_pts"]), float(round(abs(t["gap_pts"])))}
    findings = []
    for m in NUM.finditer(text):
        v = float(m.group(1))
        if not any(abs(v - a) < 0.051 for a in allowed):
            findings.append(f"untraced percentage {m.group(0)!r}")
    for m in OF.finditer(text):
        if (int(m.group(1)), int(m.group(2))) not in pairs:
            findings.append(f"untraced count pair {m.group(0)!r}")
    low = text.casefold()
    w = d["weakest"]
    if w:
        if w["from"].casefold() not in low or w["to"].casefold() not in low:
            findings.append(
                f"does not name the weakest transition {w['from']} -> {w['to']}"
            )
    elif "no single bottleneck" not in low:
        findings.append(
            "no transition is below range, yet the text does not say 'no single bottleneck'"
        )
    return findings


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("diagnose", "write", "check"):
        p = sub.add_parser(name)
        p.add_argument("funnel", nargs="?", type=Path, default=DEFAULT_CSV)
        p.add_argument("--benchmarks", type=Path, default=DEFAULT_BENCH)
        if name == "diagnose":
            p.add_argument("--json", type=Path)
        else:
            p.add_argument("--prompt", type=Path, default=DEFAULT_PROMPT)
    n = sub.add_parser("check-narrative")
    n.add_argument("text", type=Path)
    n.add_argument("--diagnosis", type=Path, required=True)
    args = ap.parse_args(argv)

    try:
        if args.cmd == "check-narrative":
            d = json.loads(args.diagnosis.read_text(encoding="utf-8"))
            findings = check_narrative(args.text.read_text(encoding="utf-8"), d)
            for f in findings:
                print(f"FINDING {f}")
            print(f"check-narrative: {len(findings)} finding(s)")
            return 1 if findings else 0
        d = diagnose(args.funnel, args.benchmarks)
    except (ValueError, OSError, KeyError) as exc:
        print(f"funnel_answer_key: {exc}", file=sys.stderr)
        return 2

    block = render_block(d, _rel(args.funnel), _rel(args.benchmarks))
    if args.cmd == "diagnose":
        print(block)
        if args.json:
            args.json.write_text(json.dumps(d, indent=2) + "\n", encoding="utf-8")
        return 0
    text = args.prompt.read_text(encoding="utf-8")
    try:
        start, end = _embedded(text)
    except ValueError as exc:
        print(f"funnel_answer_key: {exc}", file=sys.stderr)
        return 2
    current = text[start:end]
    if args.cmd == "check":
        if current != block:
            print(
                f"check: the answer key in {args.prompt.name} drifted from the data; run `write`"
            )
            return 1
        print(f"check: the answer key in {args.prompt.name} matches the data")
        return 0
    args.prompt.write_text(text[:start] + block + text[end:], encoding="utf-8")
    print(f"write: answer key refreshed in {args.prompt.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
